import { FORECAST_VERSION, HORIZONS_MIN, QUANTITIES } from '@gateflow/forecast';
import type { Calibration, PitSets, Quantity } from '@gateflow/forecast';
import { MODEL_VERSION } from '@gateflow/sim-model';
import { GENERATOR_VERSION } from '@gateflow/sim-scenarios';
import { calibrationOfDays } from './backtest';
import { normaliseSeeds } from './experiment';
import { formatSeedRanges, roundNumbers } from './results';

/*
 * The calibration of the forecasts' bands on the scenario library (S21.3, ADR-055): where the
 * truths fell among the paths, on simulated days set apart for it, gives the levels at which the
 * bands' edges read the paths. The levels are code: `gateflow-sim calibrate` writes them as a
 * module of the forecast package, and CI checks that the module is what the library gives.
 */

export const CALIBRATION_SCHEMA = 'gateflow.forecast.calibration/1';

/**
 * The days calibrations are fitted on: never a day of the reports (from 1), of the forecasts'
 * profile (from 1,000,001) or of the tuning of S21 (1001 to 1020).
 */
export const CALIBRATION_FIRST_SEED = 2_000_001;
export const CALIBRATION_DAYS = 60;

/** A calibration of the library, as `gateflow-sim calibrate` writes it. */
export interface CalibrationDocument {
  readonly schema: string;
  readonly generator: { readonly name: string; readonly version: string };
  readonly versions: {
    readonly forecast: string;
    readonly model: string;
    readonly populationGenerator: string;
  };
  readonly scenarios: readonly {
    readonly id: string;
    readonly hash: string;
    readonly policy: string;
  }[];
  readonly seeds: { readonly count: number; readonly ranges: string };
  /** The truths behind each level: every forecast of the arrivals, the forecasts of a queue. */
  readonly truths: Readonly<Record<Quantity, Readonly<Record<string, number>>>>;
  readonly levels: Calibration['levels'];
}

/** The calibration of simulated days of several scenarios, pooled. */
export function buildCalibration(
  input: {
    readonly scenarios: readonly {
      readonly id: string;
      readonly hash: string;
      readonly policy: string;
    }[];
    readonly seeds: readonly number[];
    readonly generator: { readonly name: string; readonly version: string };
  },
  days: readonly PitSets[],
): CalibrationDocument {
  const seeds = normaliseSeeds(input.seeds);
  const truths = {} as Record<Quantity, Record<string, number>>;
  for (const quantity of QUANTITIES) {
    truths[quantity] = Object.fromEntries(
      HORIZONS_MIN.map((h) => [
        String(h),
        days.reduce((n, day) => n + (day[quantity][String(h)]?.length ?? 0), 0),
      ]),
    );
  }
  return {
    schema: CALIBRATION_SCHEMA,
    generator: input.generator,
    versions: {
      forecast: FORECAST_VERSION,
      model: MODEL_VERSION,
      populationGenerator: GENERATOR_VERSION,
    },
    scenarios: input.scenarios.map((s) => ({ id: s.id, hash: s.hash, policy: s.policy })),
    seeds: { count: seeds.length, ranges: formatSeedRanges(seeds) },
    truths,
    levels: roundNumbers(calibrationOfDays(days)).levels,
  };
}

/** The calibration as a module of the forecast package: what `--check` compares, byte for byte. */
export function renderCalibrationModule(doc: CalibrationDocument): string {
  const lines = [
    '// Generated by `pnpm calibrate:library` (gateflow-sim calibrate, S21.3): do not edit by hand.',
    '// CI checks that it is what the scenario library gives (ADR-055).',
    "import type { Calibration } from './calibration';",
    '',
    '/**',
    " * The bands' calibration on the scenario library: on simulated days set apart for it (seeds",
    ` * ${doc.seeds.ranges}, ${String(doc.seeds.count)} per scenario), where the truths fell among the paths.`,
    ' * Scenarios:',
    ...doc.scenarios.map((s) => ` * - ${s.id} (${s.policy}, ${s.hash.slice(0, 19)}...)`),
    ` * Forecast ${doc.versions.forecast}, model ${doc.versions.model}, population generator ${doc.versions.populationGenerator}.`,
    ' */',
    `export const LIBRARY_CALIBRATION: Calibration = ${JSON.stringify({ levels: doc.levels }, null, 2)};`,
    '',
    '/** Where {@link LIBRARY_CALIBRATION} comes from, as documents cite it. */',
    `export const LIBRARY_CALIBRATION_SOURCE = ${JSON.stringify(
      `the scenario library (${String(doc.scenarios.length)} scenarios, seeds ${doc.seeds.ranges})`,
    )};`,
    '',
    '/** The truths behind each level of {@link LIBRARY_CALIBRATION}. */',
    `export const LIBRARY_CALIBRATION_TRUTHS = ${JSON.stringify(doc.truths, null, 2)} as const;`,
    '',
  ];
  return lines.join('\n');
}
